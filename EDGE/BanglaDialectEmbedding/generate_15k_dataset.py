# Templates for expansion (multiply base sentences)
def expand_sentences(base_sentences):
    """Expand sentences with variations."""
    expanded = list(base_sentences)

    time_variations = [
        ("এই মাসে", "এই মাসে"),
        ("এই বছরে", "এই বছরে"),
        ("সবসময়", "সবসময়"),
        ("প্রায়ই", "প্রায়ই"),
        ("অনেক আগে", "অনেক আগে"),
        ("আজকাল", "আজকাল"),
    ]

    adverb_variations = [
        ("খুব", "খুব"),
        ("একটু", "একটু"),
        ("বেশি", "বেশি"),
        ("কম", "কম"),
        ("অনেক", "অনেক"),
    ]

    for dialect, standard, region in base_sentences[:50]:  # expand first 50
        # Time variations
        for time_d, time_s in time_variations:
            new_dial = f"{time_d} {dialect}"
            new_std = f"{time_s} {standard}"
            if len(new_dial.split()) >= 5:
                expanded.append((new_dial, new_std, region))

        # Adverb variations
        for adv_d, adv_s in adverb_variations:
            new_dial = f"{dialect} {adv_d}"
            new_std = f"{standard} {adv_s}"
            if len(new_dial.split()) >= 5:
                expanded.append((new_dial, new_std, region))

    return expanded

