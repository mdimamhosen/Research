# Now create additional synthetic variations from structure
def create_synthetic_variations(base_list, target_count=15000):
    """Generate synthetic variations maintaining semantic meaning."""
    current = list(base_list)

    # Additional pattern variations
    patterns = {
        "dhakaia": [
            " এবং বলেছেন যে",
            " যেন সবাই দেখে",
            " তাই আমি বলছি",
            " কিন্তু এটা সত্যি",
            " সেইজন্য আমরা করি",
        ],
        "chottogrami": [
            " রে ভাই বলছি",
            " এত বেশি দেখা",
            " তাই রে সবাই",
            " কারণ রাস্তা ভালো",
            " রে ভাই সত্যি",
        ],
        "sylheti": [
            " থাইকে দেখা যায়",
            " সত্যি রে ভাই",
            " করিস ভালো করে",
            " অহন অনেক",
            " থাইকে আসছি আমরা",
        ],
    }

    # Generate variations with patterns
    for region, pattern_list in patterns.items():
        region_pairs = [p for p in base_list if p[2] == region]

        for pattern in pattern_list:
            for dial, std, reg in region_pairs[:len(region_pairs)//2]:
                if len(current) < target_count:
                    # Add pattern to middle of sentence
                    parts_d = dial.rsplit(' ', 2)
                    if len(parts_d) >= 2:
                        new_dial = f"{' '.join(parts_d[:-1])}{pattern} {parts_d[-1]}"
                        new_std = f"{' '.join(std.rsplit(' ', 2)[:-1])}{pattern.replace('রে ভাই', '').replace('থাইকে', 'থেকে')} {std.rsplit(' ', 2)[-1]}"
                        if len(new_dial.split()) >= 5:
                            current.append((new_dial, new_std, reg))

    return current[:target_count]

