# Generate final dataset
all_pairs = []
region_counts = defaultdict(int)

for region_key, region_data in REGION_DATA.items():
    print(f"\n{region_data['name']}: {region_data['description']}")

    for dialect, standard in region_data['sentences']:
        # Verify at least 5 words
        dialect_words = len(dialect.split())
        standard_words = len(standard.split())

        if dialect_words >= 5 and standard_words >= 5:
            all_pairs.append((dialect, standard, region_key))
            region_counts[region_key] += 1
        else:
            pass  # Skip short sentences silently

    print(f"  Added {region_counts[region_key]} sentences")

print(f"\n{'='*60}")
print(f"Total sentences by region:")
for region_key in REGION_DATA.keys():
    print(f"  {REGION_DATA[region_key]['name']:20s}: {region_counts[region_key]:4d}")
print(f"{'='*60}")
print(f"TOTAL: {len(all_pairs)} pairs")

# Shuffle while preserving region info
random.shuffle(all_pairs)

# Write to file with region tags
output_file = r"C:\Error\Research\EDGE\BanglaDialectSSM\corpus\raw\pairs.tsv"

with open(output_file, 'w', encoding='utf-8') as f:
    f.write("# dialect_sentence\t\tstandard_bangla_sentence\t\tregion\n")
    f.write("# Enriched Bangla Dialect Dataset - Region-specific meaningful sentences\n")
    f.write("# Regions: dhakaia, chottogrami, sylheti, barishallia, khulnaia, rajshahi, rangpuri\n")
    f.write("# Each sentence has minimum 5 words for semantic meaningfulness\n\n")

    for dialect, standard, region in all_pairs:
        f.write(f"{dialect}\t{standard}\t{region}\n")

print(f"\nSuccessfully wrote {len(all_pairs)} meaningful region-tagged pairs")
print(f"Output file: {output_file}")

